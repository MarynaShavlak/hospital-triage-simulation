"""Модель даних та спільні константи.

Шкала тяжкості — реальна **Emergency Severity Index (ESI)**:

| Рівень | Значення         | Приклад                  |
|--------|------------------|--------------------------|
| 1      | Реанімація       | зупинка серця            |
| 2      | Невідкладний     | інсульт, сильна кровотеча|
| 3      | Терміновий       | перелом, висока темп.    |
| 4      | Менш терміновий  | розтягнення              |
| 5      | Нетерміновий     | подряпина, довідка       |

Чим **менше** число — тим **тяжчий** пацієнт і тим **вищий** його пріоритет.
"""
from __future__ import annotations

from dataclasses import dataclass

# Канонічний набір рівнів тяжкості (ESI 1..5) — єдине джерело для ітерації.
SEVERITY_LEVELS = (1, 2, 3, 4, 5)
N_LEVELS = len(SEVERITY_LEVELS)

# Кольори та назви рівнів тяжкості (шкала ESI) — знадобляться всюди.
SEV_COLORS = {1: "#d32f2f", 2: "#f57c00", 3: "#fbc02d", 4: "#7cb342", 5: "#43a047"}
SEV_NAMES = {
    1: "L1 Критичний",
    2: "L2 Невідкладний",
    3: "L3 Терміновий",
    4: "L4 Менш терм.",
    5: "L5 Нетерміновий",
}

# Реалістичний розподіл тяжкості: більшість випадків середні (L3–L4), критичних мало.
SEVERITY_PROBS = {1: 0.05, 2: 0.15, 3: 0.35, 4: 0.30, 5: 0.15}

# Базовий (типовий) час лікування за рівнями: чим тяжчий — тим довше.
BASE_SERVICE = {1: 25, 2: 18, 3: 12, 4: 8, 5: 5}

# Параметри розподілу часу лікування навколо базового значення.
SERVICE_NOISE = 0.25   # відносний розкид (±25 %)
MIN_SERVICE = 2.0      # захисна підлога (хв): лікування не буває миттєвим

# Поріг aging за замовчуванням (хв): за стільки очікування пацієнт «легшає» на рівень.
# Єдине джерело для всіх рушіїв aging; обґрунтування підбору — у docs/05-aging.md.
DEFAULT_AGING_THRESHOLD = 45

# Канонічний порядок дисциплін обслуговування — єдине джерело для бібліотеки,
# скриптів і figbuild (раніше дублювалося в трьох місцях).
DISCIPLINES = ("fifo", "priority", "aging")


@dataclass
class Patient:
    """Один пацієнт приймального відділення.

    Перші чотири поля — незмінні характеристики; `start_time` заповнюється під
    час симуляції. Поля-розширення (`patience` тощо) лишаються `None`, доки
    відповідна модель (reneging/deterioration) їх не заповнить — оголошені тут
    явно, щоб не «навішуватись» динамічно й щоб типи були чесними.
    """

    id: int
    arrival_time: float                      # хвилини від початку зміни
    severity: int                            # 1 = критичний ... 5 = легкий
    service_duration: float                  # скільки хвилин займе лікування
    start_time: float | None = None       # коли реально почали лікувати

    # поля-розширення моделей (заповнюються відповідними assign_*/simulate_*)
    patience: float | None = None         # reneging: поріг терпіння (хв)
    leave_time: float | None = None       # reneging: коли пішов (LWBS)
    orig_severity: int | None = None      # deterioration: тяжкість на старті
    orig_duration: float | None = None    # deterioration: час лікування на старті
    det_times: list[float] | None = None  # deterioration: моменти падіння тяжкості
    death_time: float | None = None       # deterioration: коли помер

    @property
    def wait_time(self) -> float:
        """Час очікування = коли почали лікувати − коли прибув."""
        assert self.start_time is not None, "wait_time доступний лише після обслуговування"
        return self.start_time - self.arrival_time
